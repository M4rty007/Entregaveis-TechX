PI = 3.14159


def add(a, b):        # Operador de Soma
    return a + b

def subtarct(a, b):   # Operador de Subtração
    return a - b

def multiply(a, b):   # Operador de Multiplicação
    return a * b

def devide(a, b):     # Operador de Divisão
    if b == 0:
        return None
    else:
        return a / b